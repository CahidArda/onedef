/**
 * The MCP App build: one self-contained HTML file (scripts and styles
 * inlined), because an MCP host serves the app as a single resource into a
 * sandboxed iframe with nothing beside it to fetch.
 *
 * Everything Vite needs is generated into `.onedef/mcp-app/` — the page, the
 * root that mounts the user's `defineMcpApp()` export, and a stylesheet that
 * pulls in the site's global CSS — so a Next project writes one entry file and
 * no bundler config. Loaded lazily by `withOnedef()`: `next start` and every
 * request-time config load never pay for Vite.
 */
import { existsSync } from 'node:fs'
import { mkdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import type { InlineConfig, Plugin } from 'vite'

export interface ResolvedMcpApp {
  /** The Next project directory. */
  dir: string
  /** Absolute path of the entry (`app/mcp-app.tsx`). */
  entry: string
  /** Global stylesheet to include, if any. */
  css?: string
  /** Where generated sources and the built file go: `<dir>/.onedef/mcp-app`. */
  workDir: string
  /** The built single file: `<workDir>/dist/index.html`. */
  html: string
  tailwind: boolean
  vite?: InlineConfig | ((config: InlineConfig) => InlineConfig | Promise<InlineConfig>)
}

const rel = (from: string, to: string) => {
  const relative = path.relative(from, to).split(path.sep).join('/')
  return relative.startsWith('.') ? relative : `./${relative}`
}

const WATCH_IGNORED = [
  '**/node_modules/**',
  '**/.next/**',
  '**/.onedef/**',
  '**/.git/**',
  '**/.turbo/**',
  '**/.vercel/**',
]

/** Write the page, the root and the stylesheet Vite builds from. */
export async function generate(app: ResolvedMcpApp): Promise<string> {
  await mkdir(app.workDir, { recursive: true })
  await writeFile(path.join(app.workDir, '.gitignore'), '*\n')
  const files: Record<string, string> = {
    'index.html': [
      '<!doctype html>',
      '<html lang="en">',
      '  <head>',
      '    <meta charset="utf-8" />',
      '    <meta name="viewport" content="width=device-width, initial-scale=1" />',
      '  </head>',
      '  <body>',
      '    <div id="root"></div>',
      '    <script type="module" src="./main.ts"></script>',
      '  </body>',
      '</html>',
      '',
    ].join('\n'),
    'main.ts': [
      '// Generated by @onedef/next from your MCP App entry. Do not edit.',
      ...(app.css || app.tailwind ? ["import './styles.css'"] : []),
      `import app from '${rel(app.workDir, app.entry).replace(/\.tsx?$/, '')}'`,
      "import { mount } from '@onedef/next/mcp-app'",
      '',
      'void mount(app)',
      '',
    ].join('\n'),
  }
  if (app.css || app.tailwind) {
    files['styles.css'] = [
      "/* Generated by @onedef/next: the site's global stylesheet, and the whole",
      "   project as Tailwind's source, since the build runs from this folder. */",
      ...(app.css ? [`@import "${rel(app.workDir, app.css)}";`] : []),
      ...(app.tailwind ? [`@source "${rel(app.workDir, app.dir)}";`] : []),
      '',
    ].join('\n')
  }
  for (const [name, body] of Object.entries(files)) await writeFile(path.join(app.workDir, name), body)
  return path.join(app.workDir, 'index.html')
}

/** The Vite config for an app — defaults first, then the user's `vite` escape hatch. */
export async function viteConfig(app: ResolvedMcpApp, watch: boolean): Promise<InlineConfig> {
  // resolved from this package, so a project installs nothing but @onedef/next
  const [{ mergeConfig }, react, { viteSingleFile }] = await Promise.all([
    import('vite'),
    import('@vitejs/plugin-react').then((m) => m.default),
    import('vite-plugin-singlefile'),
  ])
  const plugins: Plugin[] = [...([react()].flat() as Plugin[]), viteSingleFile() as Plugin]
  if (app.tailwind) {
    const tailwind = (await import('@tailwindcss/vite')).default
    plugins.splice(1, 0, ...([tailwind()].flat() as Plugin[]))
  }
  // what Next inlines into client code: NEXT_PUBLIC_* and NODE_ENV
  const define = Object.fromEntries(
    Object.entries(process.env)
      .filter(([name]) => name.startsWith('NEXT_PUBLIC_'))
      .map(([name, value]) => [`process.env.${name}`, JSON.stringify(value)]),
  )
  const base: InlineConfig = {
    configFile: false,
    root: app.workDir,
    base: './',
    logLevel: 'warn',
    clearScreen: false,
    mode: watch ? 'development' : 'production',
    plugins,
    define,
    resolve: {
      alias: [{ find: /^@\//, replacement: `${app.dir}/` }],
      // one React and one QueryClient context: always the app's own copies, even when
      // @onedef/next resolves its own (a linked or hoisted install) — two Reacts fail
      // at the first hook, two React Query copies never see each other's provider
      dedupe: ['react', 'react-dom', '@tanstack/react-query'],
    },
    build: {
      outDir: path.dirname(app.html),
      emptyOutDir: true,
      // Tailwind's @source covers the whole project, so the watcher would see
      // everything — including .next/, which `next dev` rewrites constantly,
      // and our own output: an endless rebuild loop. Only sources count.
      ...(watch ? { watch: { exclude: WATCH_IGNORED } } : {}),
      rollupOptions: {
        onwarn(warning, warn) {
          // "use client" marks Next client components; meaningless (and harmless) here
          if (warning.code === 'MODULE_LEVEL_DIRECTIVE') return
          warn(warning)
        },
      },
    },
  }
  const custom = typeof app.vite === 'function' ? await app.vite(base) : app.vite
  return custom ? mergeConfig(base, custom) : base
}

/** Build once (`next build`). */
export async function buildMcpApp(app: ResolvedMcpApp): Promise<void> {
  await generate(app)
  const { build } = await import('vite')
  await build(await viteConfig(app, false))
}

/** Build and keep rebuilding on change (`next dev`). Resolves once the first build is written. */
export async function watchMcpApp(
  app: ResolvedMcpApp,
  log: (message: string) => void,
): Promise<{ close(): Promise<void> }> {
  await generate(app)
  const { build } = await import('vite')
  const watcher = (await build(await viteConfig(app, true))) as unknown as {
    on(
      event: 'event',
      listener: (event: { code: string; error?: unknown; result?: { close?: () => void } }) => void,
    ): void
    close(): Promise<void>
  }
  let first = true
  await new Promise<void>((resolve) => {
    watcher.on('event', (event) => {
      if (event.code === 'END') {
        log(first ? `MCP App ready (${path.relative(app.dir, app.html)})` : 'MCP App rebuilt')
        if (first) resolve()
        first = false
      }
      if (event.code === 'ERROR') {
        log(`MCP App build failed: ${(event.error as Error)?.message ?? event.error}`)
        if (first) resolve()
        first = false
      }
      event.result?.close?.()
    })
  })
  return watcher
}

/** Is `name` installed for the project in `dir`? (Tailwind is applied only when the project uses it.) */
export function installed(dir: string, name: string): boolean {
  try {
    createRequire(path.join(dir, 'package.json')).resolve(`${name}/package.json`)
    return true
  } catch {
    return existsSync(path.join(dir, 'node_modules', name))
  }
}
